# SECTION 7: K-FOLD CROSS-VALIDATION
# ============================================================================

np.random.seed(2)
pageSpeeds = np.random.normal(3.0, 1.0, 100)
purchaseAmount = np.random.normal(50.0, 30.0, 100) / pageSpeeds

# Split into train (80) and test (20)
trainX, testX = pageSpeeds[:80], pageSpeeds[80:]
trainY, testY = purchaseAmount[:80], purchaseAmount[80:]

# 8th-degree polynomial fit
p4 = np.poly1d(np.polyfit(trainX, trainY, 8))

# Evaluate on test data
r2_test = r2_score(testY, p4(testX))
r2_train = r2_score(trainY, p4(trainX))
print(f"Train R-squared: {r2_train:.4f}")
print(f"Test R-squared: {r2_test:.4f}")

# Find best polynomial degree (1-10) using test R-squared
degrees = range(1, 11)
r2_scores = []

for degree in degrees:
    p = np.poly1d(np.polyfit(trainX, trainY, degree))
    r2 = r2_score(testY, p(testX))
    r2_scores.append(r2)

best_degree = degrees[np.argmax(r2_scores)]
best_r2 = max(r2_scores)
print(f"Best degree: {best_degree}, R-squared: {best_r2:.4f}")

