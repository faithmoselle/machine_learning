# SECTION 1: SIMPLE LINEAR REGRESSION
# ============================================================================

# %matplotlib inline
import numpy as np
from pylab import *

# Generate synthetic data: page speeds (normal distribution, mean=3.0, std=1.0, n=1000)
pageSpeeds = np.random.normal(3.0, 1.0, 1000)

# Purchase amount inversely related to page speed with noise
# Formula: 100 - (pageSpeed + noise) * 2
purchaseAmount = 100 - (pageSpeeds + np.random.normal(0, 0.1, 1000)) * 2

# Scatter plot to visualize relationship
scatter(pageSpeeds, purchaseAmount)
plt.title('Page Speed vs Purchase Amount')
plt.xlabel('Page Speed (seconds)')
plt.ylabel('Purchase Amount ($)')
plt.show()

# Perform linear regression using scipy
from scipy import stats
slope, intercept, r_value, p_value, std_err = stats.linregress(pageSpeeds, purchaseAmount)

# R-squared: Proportion of variance explained by the model (0-1, higher = better)
r_squared = r_value ** 2
print(f"R-squared: {r_squared:.4f}")

# Prediction function: y = mx + c
def predict(x):
    return slope * x + intercept

# Plot regression line over scatter plot
import matplotlib.pyplot as plt
fitline = predict(pageSpeeds)

plt.scatter(pageSpeeds, purchaseAmount)
plt.plot(pageSpeeds, fitline, c='r', label='Regression Line')
plt.title('Linear Regression Fit')
plt.xlabel('Page Speed')
plt.ylabel('Purchase Amount')
plt.legend()
plt.show()

"""
YOUR TURN: Increasing Variation
Try increasing the random variation in the test data, and see what effect 
it has on the r-squared error value.

OBSERVATION: Higher noise decreases R-squared because the model cannot 
explain the additional random variance in the data.
"""

# ============================================================================
