# SECTION 8: SVM KERNEL COMPARISON
# ============================================================================

from sklearn.model_selection import cross_val_score, train_test_split
from sklearn import datasets
from sklearn import svm

iris = datasets.load_iris()
X_train, X_test, y_train, y_test = train_test_split(iris.data, iris.target, test_size=0.4, random_state=0)

# 5-Fold Cross-Validation with SVM
clf = svm.SVC(kernel='sigmoid', C=1).fit(X_train, y_train)
print(f"Test score (sigmoid): {clf.score(X_test, y_test):.4f}")

scores = cross_val_score(clf, iris.data, iris.target, cv=5)
print(f"5-Fold CV scores: {scores}")
print(f"Mean CV score: {scores.mean():.4f}")

# Compare different SVM kernels
kernels = ['linear', 'poly', 'rbf', 'sigmoid']
kernel_scores = []

for kernel in kernels:
    clf = svm.SVC(kernel=kernel, C=1).fit(X_train, y_train)
    score = clf.score(X_test, y_test)
    kernel_scores.append(score)

results = pd.DataFrame({'Kernel': kernels, 'Score': kernel_scores})
print(results)
best_kernel = results.loc[results['Score'].idxmax()]
print(f"Best kernel: {best_kernel['Kernel']} with score: {best_kernel['Score']:.4f}")
