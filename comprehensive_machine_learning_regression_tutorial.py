X[['Mileage', 'Cylinder', 'Liter', 'Doors']] = X_scaled

# Ordinary Least Squares regression
est = sm.OLS(y, X).fit()
print(est.summary())

# Average price by number of doors
print(y.groupby(df.Doors).mean())

# Predict price for a specific car (45,000 miles, 8 cylinders, 4 liters, 4 doors)
scaled = scaler.transform([[45000, 8, 4, 4]])
predicted = est.predict(scaled[0])
print(f"Predicted price: ${predicted[0]:,.2f}")

