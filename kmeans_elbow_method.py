# ============================================================================
# PART 1: LOAD AND EXPLORE IRIS DATASET
# ============================================================================
import numpy as np
import pandas as pd
import matplotlib.pyplot as plt
from sklearn import datasets

# Load Iris dataset (150 samples, 4 features)
iris = datasets.load_iris()
iris_df = pd.DataFrame(iris.data, columns=iris.feature_names)
iris_df['target'] = iris.target  # Add target column (species)
iris_df.head()  # Display first 5 rows

# Extract feature values (all 4 numeric columns)
x = iris_df.iloc[:, [0, 1, 2, 3]].values

# ============================================================================
# PART 2: ELBOW METHOD - FIND OPTIMAL NUMBER OF CLUSTERS
# ============================================================================
from sklearn.cluster import KMeans

# Calculate WCSS (Within-Cluster Sum of Squares) for k = 1 to 10
wcss = []
for i in range(1, 11):
    kmeans = KMeans(n_clusters=i, random_state=42)
    kmeans.fit(x)
    wcss.append(kmeans.inertia_)  # inertia_ = WCSS

# Plot elbow curve
plt.plot(range(1, 11), wcss, marker='o')
plt.title('The Elbow Method for Optimal k')
plt.xlabel('Number of Clusters (k)')
plt.ylabel('WCSS (Within-Cluster Sum of Squares)')
plt.grid(True)
plt.show()
# OBSERVATION: Elbow appears at k=3 (optimal number of clusters)

# ============================================================================
# PART 3: TRAIN K-MEANS WITH OPTIMAL K=3
# ============================================================================
# Create and train K-Means model with 3 clusters
kmeans = KMeans(n_clusters=3, random_state=42)
kmeans_model = kmeans.fit(x)

# Predict cluster for each data point
y_kmeans = kmeans_model.predict(x)

# ============================================================================
# PART 4: VISUALIZE CLUSTERS AND CENTROIDS
# ============================================================================
plt.figure(figsize=(15, 6))

# Plot clusters (using Sepal Length vs Sepal Width for visualization)
plt.scatter(x[y_kmeans == 0, 0], x[y_kmeans == 0, 1], s=100, c='red', label='Cluster 0')
plt.scatter(x[y_kmeans == 1, 0], x[y_kmeans == 1, 1], s=100, c='blue', label='Cluster 1')
plt.scatter(x[y_kmeans == 2, 0], x[y_kmeans == 2, 1], s=100, c='green', label='Cluster 2')

# Plot cluster centroids
plt.scatter(kmeans.cluster_centers_[:, 0], kmeans.cluster_centers_[:, 1], 
            s=200, c='yellow', marker='X', label='Centroids', edgecolors='black')

plt.xlabel('Sepal Length (cm)')
plt.ylabel('Sepal Width (cm)')
plt.title('K-Means Clustering of Iris Dataset (k=3)')
plt.legend()
plt.show()

# ============================================================================
# PART 5: PREDICT CLUSTER FOR NEW DATA POINT
# ============================================================================
# Predict which cluster a new flower belongs to
new_flower = [[1.2, 3.4, 5.5, 6.7]]
predicted_cluster = kmeans_model.predict(new_flower)[0]
print(f"New flower (sepal length=1.2, sepal width=3.4, petal length=5.5, petal width=6.7)")
print(f"Assigned to cluster: {predicted_cluster}")

