# CHALLENGE: SYNTHETIC CUSTOMER DATA CLUSTERING
# ============================================================================
"""
Create synthetic customer data with two features:
- Income (centroids between $20,000 and $200,000)
- Age (centroids between 20 and 70 years)
Use K-Means to identify customer segments
"""

from numpy import random, array

def createClusteredData(N, k):
    """
    Generate synthetic clustered data with k clusters.
    
    Args:
        N: Total number of data points
        k: Number of clusters
    
    Returns:
        X: Array of shape (N, 2) with [income, age] pairs
    """
    random.seed(10)
    pointsPerCluster = float(N) / k
    X = []
    
    for i in range(k):
        # Random centroids for income and age
        incomeCentroid = random.uniform(20000.0, 200000.0)
        ageCentroid = random.uniform(20.0, 70.0)
        
        # Generate points around centroids with normal distribution
        for j in range(int(pointsPerCluster)):
            X.append([
                random.normal(incomeCentroid, 10000.0),  # Income with std 10,000
                random.normal(ageCentroid, 2.0)         # Age with std 2
            ])
    
    return array(X)


# Generate synthetic customer data (100 points, 5 clusters)
data = createClusteredData(100, 5)

# Scale the data for better clustering
from sklearn.preprocessing import scale

# Apply K-Means with 5 clusters
model = KMeans(n_clusters=5, random_state=42)
model = model.fit(scale(data))

print("Cluster labels for each customer:")
print(model.labels_)

# Visualize customer segments
plt.figure(figsize=(8, 6))
plt.scatter(data[:, 0], data[:, 1], c=model.labels_.astype(float), cmap='viridis')
plt.scatter(model.cluster_centers_[:, 0], model.cluster_centers_[:, 1], 
            s=200, c='red', marker='X', label='Centroids')
plt.xlabel('Annual Income ($)')
plt.ylabel('Age (years)')
plt.title('Customer Segmentation using K-Means Clustering (k=5)')
plt.colorbar(label='Cluster')
plt.legend()
plt.show()

# Additional prediction example
print(f"\nPrediction for new flower (same as above): {predicted_cluster}")
