import pandas as pd
df = pd.read_excel('cars.xls')

# %matplotlib inline
import numpy as np

# Select Mileage and Price columns, group by mileage bins
df1 = df[['Mileage', 'Price']]
bins = np.arange(0, 50000, 10000)
groups = df1.groupby(pd.cut(df1['Mileage'], bins)).mean()
print(groups.head())

# Plot average price by mileage group
groups['Price'].plot.line()
plt.title('Average Price by Mileage Range')
plt.xlabel('Mileage Range')
plt.ylabel('Average Price ($)')
plt.show()

# ============================================================================
# MULTIPLE REGRESSION WITH FEATURE SCALING
# ============================================================================

import statsmodels.api as sm
from sklearn.preprocessing import StandardScaler

# Features: Mileage, Cylinder, Liter, Doors
# Target: Price
X = df[['Mileage', 'Cylinder', 'Liter', 'Doors']]
y = df['Price']

# Scale features to same range for coefficient comparison
scaler = StandardScaler()
X_scaled = scaler.fit_transform(X)

# Convert back to DataFrame with same column names
X[['Mileage', 'Cylinder', 'Liter', 'Doors']] = X_scaled

print(X.head())

# Ordinary Least Squares regression
est = sm.OLS(y, X).fit()
print(est.summary())

# Group average price by number of doors
print(y.groupby(df.Doors).mean())

# Predict price for a specific car
# 45000 miles, 8 cylinders, 4 liters, 4 doors
scaled = scaler.transform([[45000, 8, 4, 4]])
print(f"Scaled features: {scaled}")

predicted_price = est.predict(scaled[0])
print(f"Predicted price: ${predicted_price[0]:,.2f}")

