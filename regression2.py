# ============================================================================
# PART 1: SIMPLE LINEAR REGRESSION WITH SYNTHETIC DATA
# ============================================================================

# %matplotlib inline
import numpy as np
from pylab import *

# Generate synthetic data: page speeds (normal distribution, mean=3.0, std=1.0, n=1000)
pageSpeeds = np.random.normal(3.0, 1.0, 1000)

# Purchase amount inversely related to page speed with some noise
purchaseAmount = 100 - (pageSpeeds + np.random.normal(0, 0.1, 1000)) * 2

# Scatter plot to visualize relationship
scatter(pageSpeeds, purchaseAmount)

# Perform linear regression using scipy
from scipy import stats
slope, intercept, r_value, p_value, std_err = stats.linregress(pageSpeeds, purchaseAmount)

# Calculate R-squared (coefficient of determination)
r_squared = r_value ** 2
print(f"R-squared: {r_squared}")

# Create prediction function
import matplotlib.pyplot as plt

def predict(x):
    return slope * x + intercept

fitLine = predict(pageSpeeds)

# Plot regression line
plt.scatter(pageSpeeds, purchaseAmount)
plt.plot(pageSpeeds, fitLine, c='r')
plt.title('Linear Regression: Page Speed vs Purchase Amount')
plt.xlabel('Page Speed (seconds)')
plt.ylabel('Purchase Amount ($)')
plt.show()

