# ============================================================================
# PART 2: POLYNOMIAL REGRESSION (Non-linear relationships)
# ============================================================================

# %matplotlib inline
import numpy as np
from pylab import *

np.random.seed(2)  # For reproducibility

# Generate non-linear data: purchaseAmount inversely proportional to pageSpeeds
pageSpeeds = np.random.normal(3.0, 1.0, 1000)
purchaseAmount = np.random.normal(50.0, 10.0, 1000) / pageSpeeds

scatter(pageSpeeds, purchaseAmount)
plt.title('Non-linear Relationship: Page Speed vs Purchase Amount')
plt.xlabel('Page Speed (seconds)')
plt.ylabel('Purchase Amount ($)')
plt.show()

# Fit polynomial regression (4th degree)
x = np.array(pageSpeeds)
y = np.array(purchaseAmount)

# polyfit returns coefficients, poly1d creates polynomial function
p4 = np.poly1d(np.polyfit(x, y, 4))
print(f"4th Degree Polynomial:\n{p4}")

# Visualize polynomial fit
xp = np.linspace(0, 7, 100)
plt.scatter(x, y)
plt.plot(xp, p4(xp), c='r')
plt.title('Polynomial Regression (4th Degree)')
plt.xlabel('Page Speed (seconds)')
plt.ylabel('Purchase Amount ($)')
plt.show()

# Calculate R-squared for polynomial model
from sklearn.metrics import r2_score
r2 = r2_score(y, p4(x))
print(f"R-squared (4th degree): {r2}")

