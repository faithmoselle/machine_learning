import pandas as pd
import numpy as np
from sklearn.model_selection import train_test_split
from sklearn.svm import SVC
from sklearn.metrics import classification_report, confusion_matrix
import seaborn as sns
import matplotlib.pyplot as plt

# Step 1: Create a synthetic fruits dataset
# Features: Weight (grams), Sweetness (scale 1-10)
data = {
    'Weight': [150, 120, 130, 170, 200, 180, 160, 140, 90, 110],
    'Sweetness': [7, 8, 5, 9, 6, 5, 4, 8, 3, 2],
    'Fruit': ['Apple', 'Apple', 'Banana', 'Banana', 'Orange',
              'Orange', 'Grapes', 'Grapes', 'Strawberry', 'Strawberry']
}

# Create DataFrame
fruits = pd.DataFrame(data)
print("\nFruits Dataset:")
print(fruits)

# Step 2: Prepare features and labels
X = fruits[['Weight', 'Sweetness']].values  # Features
y = fruits['Fruit'].values                   # Labels

# Step 3: Split into training and testing sets
X_train, X_test, y_train, y_test = train_test_split(X, y, random_state=42)

print(f"\nTraining set size: {len(X_train)}")
print(f"Testing set size: {len(X_test)}")

# Step 4: Train SVM model
fruit_model = SVC(kernel='rbf', class_weight='balanced')
fruit_model.fit(X_train, y_train)

# Step 5: Make predictions
y_pred = fruit_model.predict(X_test)

# Step 6: Evaluate model
print("\nClassification Report (Fruits):")
print(classification_report(y_test, y_pred))

# Confusion Matrix for Fruits
conf_mat_fruits = confusion_matrix(y_test, y_pred)

# Plot confusion matrix heatmap
plt.figure(figsize=(8, 6))
sns.heatmap(conf_mat_fruits, annot=True, fmt='d', cbar=True,
            xticklabels=np.unique(y),
            yticklabels=np.unique(y))
plt.xlabel('Predicted')
plt.ylabel('Actual')
plt.title('Confusion Matrix - Fruit Classification')
plt.show()

print("\nSeatwork Complete: SVM successfully implemented on synthetic fruit dataset!")
