# ============================================================================
# PART 5: K-FOLD CROSS-VALIDATION WITH SVM ON IRIS DATASET
# ============================================================================

import numpy as np
from sklearn.model_selection import cross_val_score, train_test_split
from sklearn import datasets
from sklearn import svm

# Load the classic Iris dataset (150 samples, 3 classes)
iris = datasets.load_iris()

# Regular train/test split (60/40)
X_train, X_test, y_train, y_test = train_test_split(
    iris.data, iris.target, test_size=0.4, random_state=0
)

# Train SVM classifier with sigmoid kernel
clf = svm.SVC(kernel='sigmoid', C=1).fit(X_train, y_train)

# Evaluate on test set
test_score = clf.score(X_test, y_test)
print(f"\nSingle Train/Test Split Score: {test_score}")

# ============================================================================
# K-FOLD CROSS-VALIDATION (5 folds)
# ============================================================================

"""
K-Fold Cross-Validation (cv=5):
- Splits data into 5 equal parts (folds)
- Trains on 4 folds, tests on 1 fold
- Repeats 5 times, each fold used as test once
- Returns array of 5 scores
"""

scores = cross_val_score(clf, iris.data, iris.target, cv=5)

print(f"\n5-Fold Cross-Validation Scores: {scores}")
print(f"Mean Cross-Validation Score: {scores.mean():.4f}")
print(f"Standard Deviation: {scores.std():.4f}")
