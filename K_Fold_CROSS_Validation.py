# ============================================================================
# PART 1: SYNTHETIC DATA GENERATION (Non-linear relationship)
# ============================================================================

# %matplotlib inline
import numpy as np
from pylab import *

np.random.seed(2)  # For reproducibility

# Generate synthetic data: page speeds (normal distribution)
pageSpeeds = np.random.normal(3.0, 1.0, 100)

# Purchase amount inversely proportional to page speed (non-linear)
purchaseAmount = np.random.normal(50.0, 30.0, 100) / pageSpeeds

# Scatter plot to visualize relationship
scatter(pageSpeeds, purchaseAmount)
plt.title('Page Speed vs Purchase Amount (Non-linear)')
plt.xlabel('Page Speed (seconds)')
plt.ylabel('Purchase Amount ($)')
plt.show()

# ============================================================================
# PART 2: TRAIN/TEST SPLIT (80/20)
# ============================================================================

# Split data: first 80 for training, last 20 for testing
trainX = pageSpeeds[:80]
testX = pageSpeeds[80:]

trainY = purchaseAmount[:80]
testY = purchaseAmount[80:]

# Visualize training data
scatter(trainX, trainY)
plt.title('Training Data (80 samples)')
plt.xlabel('Page Speed')
plt.ylabel('Purchase Amount')
plt.show()

# Visualize test data
scatter(testX, testY)
plt.title('Test Data (20 samples)')
plt.xlabel('Page Speed')
plt.ylabel('Purchase Amount')
plt.show()

# ============================================================================
# PART 3: POLYNOMIAL REGRESSION (Degree 8)
# ============================================================================

x = np.array(trainX)
y = np.array(trainY)

# Fit 8th degree polynomial to training data
p4 = np.poly1d(np.polyfit(x, y, 8))

import matplotlib.pyplot as plt

# Generate smooth x values for plotting
xp = np.linspace(0, 7, 100)

# Plot training data and polynomial fit
axes = plt.axes()
axes.set_xlim([0, 7])
axes.set_ylim([0, 200])
plt.scatter(x, y)
plt.plot(xp, p4(xp), c='r')
plt.title('Polynomial Regression (Degree 8) on Training Data')
plt.xlabel('Page Speed')
plt.ylabel('Purchase Amount')
plt.show()

# ============================================================================
# PART 4: EVALUATE ON TEST DATA
# ============================================================================

testx = np.array(testX)
testy = np.array(testY)

# Plot test data with the same polynomial model
axes = plt.axes()
axes.set_xlim([0, 7])
axes.set_ylim([0, 200])
plt.scatter(x, y)
plt.plot(xp, p4(xp), c='r')
plt.title('Same Model Applied to Test Data')
plt.xlabel('Page Speed')
plt.ylabel('Purchase Amount')
plt.show()

from sklearn.metrics import r2_score

# Calculate R² on test data (how well model generalizes)
r2_test = r2_score(testy, p4(testx))
print(f"R-squared on TEST data: {r2_test}")

# Calculate R² on training data (how well model fits)
r2_train = r2_score(np.array(trainY), p4(np.array(trainX)))
print(f"R-squared on TRAIN data: {r2_train}")

